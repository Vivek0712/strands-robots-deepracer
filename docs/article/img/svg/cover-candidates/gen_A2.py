MARK_P = 0.80                                 # marker position on the scale (green zone)
CAR = dict(left=313, top=28, w=839)           # render scale 0.9

def ang(p): return A0 - (A0 - A1) * p
def pt(a, k=1.0):
    t = math.radians(a); return CX + k * RX * math.cos(t), CY + k * RY * math.sin(t)
def arc(p0, p1, k=1.0):
    (x0, y0), (x1, y1) = pt(ang(p0), k), pt(ang(p1), k)
    return f"M{x0:.1f} {y0:.1f} A{RX*k:.1f} {RY*k:.1f} 0 0 0 {x1:.1f} {y1:.1f}"
