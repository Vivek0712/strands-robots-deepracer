def layer(width, colour_idx, extra=""):
    return "\n".join(f'<path d="{arc(a, b)}" stroke="{s[colour_idx]}" stroke-width="{width}"{extra}/>' for s in segs for a, b in [s[:2]])
ticks = []
for p in (.35, .65):
    (x0, y0), (x1, y1) = pt(ang(p), .91), pt(ang(p), 1.09)
